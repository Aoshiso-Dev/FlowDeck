class GuitionSt77916 final : public Arduino_ST77916 {
public:
    GuitionSt77916(Arduino_DataBus* bus, int8_t reset, uint8_t rotation)
        : Arduino_ST77916(bus, reset, rotation, true, 360, 360) {}

protected:
    void tftInit() override {
        pinMode(_rst, OUTPUT);
        digitalWrite(_rst, LOW);
        delay(10);
        digitalWrite(_rst, HIGH);
        delay(ST77916_RST_DELAY);
        // Match esp_lcd_st77916: reset low 10 ms/high 120 ms, then MADCTL,
        // RGB565 COLMOD, and finally the board-specific vendor table.
        _bus->beginWrite();
        _bus->writeC8D8(ST77916_MADCTL, 0x00);
        _bus->writeC8D8(ST77916_COLMOD, 0x55);
        _bus->endWrite();
        _bus->batchOperation(GuitionSt77916Init, sizeof(GuitionSt77916Init));
        // With ips=true, false means physical INVON (0x21), matching GUITION.
        invertDisplay(false);
    }
};
